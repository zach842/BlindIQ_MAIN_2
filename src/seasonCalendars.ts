import type { WaterfowlStatusPeriod } from "./types";

type Category = WaterfowlStatusPeriod["category"];

const period = (name: string, category: Category, startDate: string, endDate: string, zone: string): WaterfowlStatusPeriod => ({
  name,
  category,
  startDate,
  endDate,
  zone,
});

